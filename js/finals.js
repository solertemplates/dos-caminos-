// Elige una frase de reserva que no se haya usado en este lote (used: lista que se guarda con el lote).
export function pickFinal(lang, used) {
  const list = FINALS[lang === 'en' ? 'en' : 'es'];
  let pool = list.filter((f) => !used.includes(f));
  if (!pool.length) pool = list; // solo si un lote tuviera más de 60 guiones sin título
  const f = pool[Math.floor(Math.random() * pool.length)];
  used.push(f);
  return f;
}
